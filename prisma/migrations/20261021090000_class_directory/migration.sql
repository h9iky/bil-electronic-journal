-- Справочник классов: имя = номер (7–11) + латинская буква (A–E).
--
-- Существующий демо-класс «10А» записан кириллицей и с прошлогодним годом —
-- переводим его в латиницу и актуальный учебный год. Остальные данные
-- (ученики, оценки, расписание) остаются на месте: меняется только ярлык.
UPDATE "Klass" SET "name" = '10A', "year" = '2026/2027' WHERE "name" = '10А';

-- Класс с одним именем в одном учебном году — один.
CREATE UNIQUE INDEX "Klass_name_year_key" ON "Klass"("name", "year");
